static uint32_t vga_to_rgb(uint8_t vga_color) {
    static const uint32_t pal[16] = {
        0x000000, 0x0000AA, 0x00AA00, 0x00AAAA,
        0xAA0000, 0xAA00AA, 0xAA5500, 0xAAAAAA,
        0x555555, 0x5555FF, 0x55FF55, 0x55FFFF,
        0xFF5555, 0xFF55FF, 0xFFFF55, 0xFFFFFF
    };
    return pal[vga_color & 0x0F];
}

static void fb_put_pixel(uint32_t x, uint32_t y, uint32_t rgb) {
    if (!g_fb.active || x >= g_fb.width || y >= g_fb.height) return;
    uint8_t* p = (uint8_t*)g_fb.addr + y * g_fb.pitch + x * (g_fb.bpp / 8);
    if (g_fb.bpp == 32 || g_fb.bpp == 24) {
        p[0] = (uint8_t)(rgb & 0xFF);
        p[1] = (uint8_t)((rgb >> 8) & 0xFF);
        p[2] = (uint8_t)((rgb >> 16) & 0xFF);
        if (g_fb.bpp == 32) p[3] = 0;
    }
}

/* Prefer 1x; zoom only if 1x would exceed console buffer limits. */
static uint8_t fb_pick_scale(uint32_t w, uint32_t h) {
    const uint32_t max_cols = 240;
    const uint32_t max_rows = 68;
    uint32_t cols1 = w / FB_FONT_W;
    uint32_t rows1 = h / FB_FONT_H;
    if (cols1 <= max_cols && rows1 <= max_rows) return 1;

    for (uint8_t s = 2; s <= 4; s++) {
        uint32_t cols = w / (FB_FONT_W * s);
        uint32_t rows = h / (FB_FONT_H * s);
        if (cols >= 40 && rows >= 10 && cols <= max_cols && rows <= max_rows)
            return s;
    }
    return 1;
}

bool fb_init_from_multiboot(uint32_t mbi_addr) {
    g_fb.active = false;
    g_fb.scale = 1;
    g_fb.origin_x = 0;
    g_fb.origin_y = 0;
    if (!mbi_addr) return false;

    uint32_t total = *(uint32_t*)mbi_addr;
    if (total < 8) return false;

    uint8_t* p = (uint8_t*)mbi_addr + 8;
    uint8_t* end = (uint8_t*)mbi_addr + total;
    while (p + 8 <= end) {
        struct mb2_tag* tag = (struct mb2_tag*)p;
        if (tag->type == MB2_TAG_END) break;
        if (tag->type == MB2_TAG_FRAMEBUFFER && tag->size >= sizeof(struct mb2_tag_framebuffer)) {
            struct mb2_tag_framebuffer* fb = (struct mb2_tag_framebuffer*)p;
            if (fb->fb_type == 1 && fb->bpp >= 24 && fb->width >= 640 && fb->height >= 480) {
                uint32_t addr32 = (uint32_t)fb->addr;
                g_fb.addr = addr32;
                g_fb.pitch = fb->pitch;
                g_fb.width = fb->width;
                g_fb.height = fb->height;
                g_fb.bpp = fb->bpp;
                g_fb.scale = fb_pick_scale(g_fb.width, g_fb.height);
                /* Map framebuffer into page tables (often above 128MB). */
                uint32_t bytes = g_fb.pitch * g_fb.height;
                if (bytes < g_fb.width * g_fb.height * (g_fb.bpp / 8))
                    bytes = g_fb.width * g_fb.height * (g_fb.bpp / 8);
                paging_map_physical(addr32, bytes + 0x1000);
                g_fb.active = true;
                log_fmt3(LOG_INFO, "fb", "framebuffer", "w", g_fb.width, "h", g_fb.height, "bpp", g_fb.bpp);
                log_fmt3(LOG_INFO, "fb", "scale", "zoom", (uint32_t)g_fb.scale,
                         "cell_w", fb_cell_width(), "cell_h", fb_cell_height());
                return true;
            }
        }
        uint32_t sz = (tag->size + 7u) & ~7u;
        if (sz < 8) break;
        p += sz;
    }
    return false;
}

const struct fb_info* fb_get_info(void) {
    return &g_fb;
}

bool fb_active(void) {
    return g_fb.active;
}

uint8_t fb_scale(void) {
    return g_fb.active ? g_fb.scale : 1;
}

uint32_t fb_cell_width(void) {
    uint8_t s = g_fb.scale ? g_fb.scale : 1;
    return (uint32_t)FB_FONT_W * s;
}

uint32_t fb_cell_height(void) {
    uint8_t s = g_fb.scale ? g_fb.scale : 1;
    return (uint32_t)FB_FONT_H * s;
}

void fb_set_console_origin(uint32_t origin_x, uint32_t origin_y) {
    g_fb.origin_x = origin_x;
    g_fb.origin_y = origin_y;
}

void fb_clear(uint32_t rgb) {
    if (!g_fb.active) return;
    for (uint32_t y = 0; y < g_fb.height; y++) {
        for (uint32_t x = 0; x < g_fb.width; x++) fb_put_pixel(x, y, rgb);
    }
}

void fb_fill_cell(size_t cell_x, size_t cell_y, uint8_t vga_color) {
    fb_draw_glyph(cell_x, cell_y, ' ', vga_color);
}

void fb_scroll_cells_up(size_t cell_row0, size_t cell_rows, size_t cell_cols,
                        size_t lines, uint8_t fill_vga) {
    if (!g_fb.active || cell_rows < 2 || lines == 0) return;
    if (lines >= cell_rows) lines = cell_rows - 1;

    uint32_t cw = fb_cell_width();
    uint32_t ch = fb_cell_height();
    uint32_t px0 = g_fb.origin_x;
    uint32_t py0 = g_fb.origin_y + (uint32_t)cell_row0 * ch;
    uint32_t width_px = (uint32_t)cell_cols * cw;
    if (px0 >= g_fb.width) return;
    if (width_px > g_fb.width - px0) width_px = g_fb.width - px0;

    uint32_t shift_px = (uint32_t)lines * ch;
    uint32_t band_px = (uint32_t)cell_rows * ch;
    if (py0 + band_px > g_fb.height) {
        if (py0 >= g_fb.height) return;
        band_px = g_fb.height - py0;
    }
    if (shift_px >= band_px) shift_px = band_px ? band_px - 1 : 0;

    uint32_t bytes_pp = g_fb.bpp / 8;
    if (bytes_pp == 0) bytes_pp = 4;
    uint8_t* base = (uint8_t*)(uintptr_t)g_fb.addr;
    uint32_t copy_h = band_px - shift_px;
    uint32_t row_bytes = width_px * bytes_pp;

    for (uint32_t y = 0; y < copy_h; y++) {
        uint8_t* dst = base + (py0 + y) * g_fb.pitch + px0 * bytes_pp;
        uint8_t* src = base + (py0 + y + shift_px) * g_fb.pitch + px0 * bytes_pp;
        for (uint32_t i = 0; i < row_bytes; i++) dst[i] = src[i];
    }

    uint32_t bg = vga_to_rgb((fill_vga >> 4) & 0x0F);
    for (uint32_t y = copy_h; y < band_px; y++) {
        for (uint32_t x = 0; x < width_px; x++)
            fb_put_pixel(px0 + x, py0 + y, bg);
    }
}

void fb_draw_glyph(size_t cell_x, size_t cell_y, char c, uint8_t vga_color) {
    if (!g_fb.active) return;
    uint8_t s = g_fb.scale ? g_fb.scale : 1;
    uint32_t cw = (uint32_t)FB_FONT_W * s;
    uint32_t ch = (uint32_t)FB_FONT_H * s;
    uint32_t px = g_fb.origin_x + (uint32_t)cell_x * cw;
    uint32_t py = g_fb.origin_y + (uint32_t)cell_y * ch;
    if (px + cw > g_fb.width || py + ch > g_fb.height) return;

    uint32_t fg = vga_to_rgb(vga_color & 0x0F);
    uint32_t bg = vga_to_rgb((vga_color >> 4) & 0x0F);

    const uint8_t* glyph = font8x8[0];
    unsigned char uc = (unsigned char)c;
    if (uc >= 0x20 && uc <= 0x7E) glyph = font8x8[uc - 0x20];

    for (int row = 0; row < 8; row++) {
        uint8_t bits = glyph[row];
        for (int dy = 0; dy < 2; dy++) {
            for (int col = 0; col < 8; col++) {
                uint32_t color = (bits & (0x80 >> col)) ? fg : bg;
                uint32_t bx = px + (uint32_t)col * s;
                uint32_t by = py + (uint32_t)(row * 2 + dy) * s;
                for (uint8_t sy = 0; sy < s; sy++)
                    for (uint8_t sx = 0; sx < s; sx++)
                        fb_put_pixel(bx + sx, by + sy, color);
            }
        }
    }
}
