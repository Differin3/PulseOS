/* Multiboot2 */
#define MB2_MAGIC 0x36d76289u
#define MB2_TAG_END 0
#define MB2_TAG_FRAMEBUFFER 8

struct mb2_tag {
    uint32_t type;
    uint32_t size;
} __attribute__((packed));

struct mb2_tag_framebuffer {
    uint32_t type;
    uint32_t size;
    uint64_t addr;
    uint32_t pitch;
    uint32_t width;
    uint32_t height;
    uint8_t bpp;
    uint8_t fb_type; /* 0=indexed, 1=RGB, 2=EGA text */
    uint16_t reserved;
} __attribute__((packed));

